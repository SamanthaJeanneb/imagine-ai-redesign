export type LocalBrandName = keyof typeof BRAND_PATHS | "imagine";

export function isLocalBrand(name: string): name is LocalBrandName {
  return name === "imagine" || Object.hasOwn(BRAND_PATHS, name);
}

export function BrandMark({
  name,
  className,
}: {
  name: LocalBrandName;
  className?: string;
}) {
  if (name === "imagine") {
    return (
      <span
        aria-hidden="true"
        className={cn("imagine-mark bg-current", className)}
      />
    );
  }

  return (
    <svg
      viewBox="0 0 24 24"
      fill="currentColor"
      aria-hidden="true"
      className={className}
    >
      <path d={BRAND_PATHS[name]} />
    </svg>
  );
}
